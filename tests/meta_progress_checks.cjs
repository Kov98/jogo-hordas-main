const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const path = require('node:path');
const storage = new Map();
const portal = { user:null, isAdmin:false, stats:{kills:0}, getProgress:()=>({forest_clears:0,castle_clears:0,catacombs_clears:0}) };
const ctx = vm.createContext({console, GamePortal:portal, localStorage:{getItem:k=>storage.get(k),setItem:(k,v)=>storage.set(k,v)}});
ctx.window = ctx;
vm.runInContext(fs.readFileSync(path.join(__dirname,'../js/data.js'),'utf8'),ctx);
const file = path.join(__dirname,'../js/meta.js');
if (fs.existsSync(file)) vm.runInContext(fs.readFileSync(file,'utf8'),ctx);
assert.equal(typeof ctx.MetaProgress,'object','MetaProgress must exist');
const M = ctx.MetaProgress;
assert.equal(M.loadout('vanguard').startPower,'slash');
assert.equal(M.choose('vanguard',{startPower:'axes',skin:'abyss'}),false,'locked rewards cannot be selected');
portal.getProgress=()=>({forest_clears:1,castle_clears:1,catacombs_clears:1});
portal.stats.kills=1000;
assert.equal(M.choose('vanguard',{startPower:'axes',skin:'abyss'}),true);
assert.equal(M.loadout('vanguard').startPower,'axes');
assert.equal(M.loadout('vanguard').skin,'abyss');
console.log('OK: milestones gate and unlock real alternative powers and appearances');
const guest = M.profileKey();
M.record({type:'secret',id:'forest-oathkeeper'},guest);
M.record({type:'secret',id:'forest-oathkeeper'},guest);
assert.equal(M.snapshot().secrets.length,1);
portal.user={id:9,username:'profile-nine'};
portal.stats.kills=0; portal.getProgress=()=>({});
assert.equal(M.loadout('vanguard').startPower,'slash');
assert(!M.unlocked().skins.includes('oathbound'));
M.record({type:'altar',id:'forest:0'},guest);
assert.equal(M.snapshot().altars.length,0,'late run event cannot leak to next account');
assert.equal(M.snapshot(guest).altars.length,1);
console.log('OK: account switching isolates choices, achievements and late run events');
M.record({type:'run',id:'one',kills:800},guest);
M.record({type:'run',id:'one',kills:800},guest);
M.record({type:'run',id:'two',kills:200},guest);
assert.equal(M.snapshot(guest).kills,1000);
console.log('OK: guest results are deduplicated and accumulate unlock progress');
portal.user=null;
assert(M.unlocked().starts.ranger.includes('frost'));
M.record({type:'evolution',id:'fire_hurricane'});
const saved = storage.get('muralha.meta.v1.guest');
const fresh = vm.createContext({GamePortal:portal, localStorage:{getItem:k=>storage.get(k),setItem:(k,v)=>storage.set(k,v)}}); fresh.window=fresh;
vm.runInContext(fs.readFileSync(path.join(__dirname,'../js/data.js'),'utf8'),fresh);
vm.runInContext(fs.readFileSync(file,'utf8'),fresh);
assert.equal(fresh.MetaProgress.snapshot().evolutions[0],'fire_hurricane');
assert(saved);
console.log('OK: reload restores permanent local progress');
const blocked = vm.createContext({GamePortal:portal,localStorage:{getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}}}); blocked.window=blocked;
vm.runInContext(fs.readFileSync(path.join(__dirname,'../js/data.js'),'utf8'),blocked);
vm.runInContext(fs.readFileSync(file,'utf8'),blocked);
assert.doesNotThrow(()=>blocked.MetaProgress.record({type:'secret',id:'forest-oathkeeper'}));
assert(blocked.MetaProgress.unlocked().skins.includes('oathbound'));
console.log('OK: blocked storage preserves an in-memory playable profile');
const player={def:{id:'vanguard'},sprite:{setTint(){return this},clearTint(){return this}}};
const restore={skin:'default',startPower:'slash'};
M.apply(player,restore);
assert.equal(player.loadout.startPower,'slash','saved checkpoint overrides current selection');
assert.equal(player.appearanceTint,null);
console.log('OK: checkpoint loadout has priority over current profile preferences');
